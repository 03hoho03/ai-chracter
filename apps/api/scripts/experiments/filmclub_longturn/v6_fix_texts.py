def replace_once(text: str, old: str, new: str, where: str) -> str:
    count = text.count(old)
    if count != 1:
        raise SystemExit(f"{where}: 바꿀 원문이 {count}번 나온다(정확히 1번이어야 한다)")
    return text.replace(old, new)
