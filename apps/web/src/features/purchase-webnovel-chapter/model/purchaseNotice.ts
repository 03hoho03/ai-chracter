/** 노벨 화를 소장하기 전의 고지 — 산 화를 언제까지 어떻게 읽고, 언제 클로버가 돌아오는가. 약관의 유료 열람 조항과
 * 같은 내용이라 문장을 바꾸면 두 곳을 함께 바꾼다. 노벨 정책 스위치(가격 응답의 `novelPublicPolicyV2Enabled`)에 따라
 * 사실이 다르다.
 *
 * - 꺼짐: 공개가 끝나면 못 보고 클로버도 돌려주지 않는다(운영자의 잘못으로 끝난 경우는 제외). 게시자가 소설을 지우면 자동으로 돌려준다.
 * - 켜짐: 게시자가 거두거나 지우거나 탈퇴해도, 판매가 멈춰도 계속 읽는다(환급 없음). 고쳐 다시 공개해도 다시 사지 않고
 *   산 때의 판과 최신 판을 골라 읽는다. 운영자의 이용제한·삭제만 열람을 끝내고 쓴 클로버를 자동으로 돌려준다.
 *
 * 값이 없으면(옛 서버·가격 응답을 아직 못 받음) 꺼짐 문장이다 — 스위치가 켜지기 전의 지금 문장과 같다. */
export type PurchaseNotice = {
  /** 본문 잉크로 두는 첫 문단 — 무엇을 사는가. */
  lead: string;
  /** 둘째 문단. 모달이 끝에 "앞 N화 무료" 문장을 이어 붙인다. */
  detail: string;
};

const OFF: PurchaseNotice = {
  lead: "구매한 화는 공개가 유지되는 동안 볼 수 있어요.",
  detail:
    "소장하면 바로 열려 구매를 취소할 수 없고, 게시자의 공개 철회·탈퇴나 원작 제한·운영 조치로 공개가 끝나도 열람에 쓴 클로버는 돌려드리지 않아요(운영자의 잘못으로 끝난 경우는 제외). 게시자가 소설을 삭제하면 클로버가 자동으로 돌아와요.",
};

const ON: PurchaseNotice = {
  lead: "소장한 화는 게시자가 고쳐 다시 공개해도 다시 살 필요가 없고, 산 때의 판과 최신 판 가운데 골라 읽을 수 있어요.",
  detail:
    "소장하면 바로 열려 구매를 취소할 수 없어요. 게시자가 공개를 거두거나 소설을 지우거나 탈퇴해도, 판매가 멈춰도 산 화는 계속 읽을 수 있고 이때 클로버는 돌려드리지 않아요. 운영자가 이 소설이나 원작을 이용제한·삭제하면 더 읽을 수 없게 되고, 쓴 클로버는 꺼낸 그대로(유효기간 포함) 자동으로 돌려드려요. 돌려받은 화는 다시 열려도 새로 소장해야 읽을 수 있어요.",
};

export function toPurchaseNotice(pricing: { novelPublicPolicyV2Enabled?: boolean } | undefined): PurchaseNotice {
  return pricing?.novelPublicPolicyV2Enabled === true ? ON : OFF;
}
