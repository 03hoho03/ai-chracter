/** 탈퇴 확인 다이얼로그의 설명 — 탈퇴하면 무엇이 어떻게 되는가. 노벨 정책 스위치(가격 응답의 `novelPublicPolicyV2Enabled`)에
 * 따라 만든 소설의 운명이 다르다.
 *
 * - 꺼짐: 만든 소설은 모두 지운다(노벨로 판 소설도 — 산 회원의 열람이 끝난다).
 * - 켜짐: 노벨로 팔린 소설(아직 돌려주지 않은 구매가 있는 소설)은 지우지 않고 작가 정보 없이 숨겨 남겨 산 회원이 계속
 *   읽는다. 산 회원에게 클로버를 돌려주지 않는다. 팔리지 않은 소설은 지금처럼 지운다.
 *
 * 값이 없으면(옛 서버·가격 응답을 아직 못 받음) 꺼짐 문장이다 — 스위치가 켜지기 전의 지금 문장과 같다. */
const OFF =
  "탈퇴하면 발행한 캐릭터·스토리는 비공개로 전환되고, 대화기록과 만든 소설은 삭제돼요. 작성 중인 초안은 보존되지만 탈퇴 후에는 접근할 수 없어요. 이 작업은 되돌릴 수 없어요.";

const ON =
  "탈퇴하면 발행한 캐릭터·스토리는 비공개로 전환되고, 대화기록과 만든 소설은 삭제돼요. 다만 노벨에서 팔린 소설은 작가 정보 없이 남아 산 회원이 계속 읽어요(산 회원에게 클로버를 돌려드리지 않아요). 작성 중인 초안은 보존되지만 탈퇴 후에는 접근할 수 없어요. 이 작업은 되돌릴 수 없어요.";

export function toWithdrawalNotice(pricing: { novelPublicPolicyV2Enabled?: boolean } | undefined): string {
  return pricing?.novelPublicPolicyV2Enabled === true ? ON : OFF;
}
