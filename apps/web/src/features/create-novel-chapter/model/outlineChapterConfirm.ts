/** 구성안으로 쓰는 화의 원고 확인 창 글. `named` 는 확인 창이 가리키는 화 이름(`「제목」 화`, 제목이 없으면 `이 화`)이다.
 *
 * `note` 는 원고를 쓴 뒤 그 화의 마지막 답을 바꾸면 생기는 일이다. 원고는 그 화 장면 근거의 원문을 기억해 두고, 다시 만들 때 원문이
 * 다르면 거절한다 — 마지막 답을 다시 생성하면 옛 답이 지워지고, 방금 전 답변으로 돌리면 지금 답이 보관으로 빠져, 어느 쪽이든 그 화의
 * 원문이 달라진다. 다시 생성한 답은 옛 답 자리가 아니라 그 뒤 시각에 들어가 담을 대화의 고른 뒤 이어진 대화로 보인다. 대화로 바로
 * 만든 화의 범위 고르는 창 안내("다시 생성한 답은 다음 화에 담겨요")와 뒤 문장이 다른 까닭이다 — 이 흐름에서는 다음 화에 저절로
 * 담기지 않는다. 대화 화면에는 알릴 자리가 없어(어느 답이 화의 끝인지 채팅 응답에 없다) 원고를 쓰기 직전에 말한다. */
export function toOutlineChapterConfirm(named: string): {
  title: string;
  description: string;
  confirmLabel: string;
  note: string;
} {
  return {
    title: "원고를 쓸까요?",
    description: `${named}를 승인한 장면 구성안대로 써요. 다 쓰면 보드에 새 화로 놓여요.`,
    confirmLabel: "원고 쓰기",
    note: "원고를 쓴 뒤 이 화에 담긴 마지막 답을 다시 생성하거나 방금 전 답변으로 돌리면 이 화는 다시 만들 수 없어요. 다시 생성한 답은 담을 대화에 고른 뒤 이어진 대화로 나타나요.",
  };
}
