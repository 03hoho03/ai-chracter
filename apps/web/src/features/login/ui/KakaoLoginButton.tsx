import { Button } from "@ai-character-chat/ui/components/button";

type KakaoLoginButtonProps = {
  onClick: () => void;
};

/** 카카오 말풍선 심볼. 카카오가 배포하는 공식 버튼 리소스(`kakao_login_light.svg`)의 path를 그대로 옮겼다 —
 * 가이드가 심볼의 형태·비율 변경을 금지해서 손으로 그리지 않는다. viewBox는 48×48 원본 캔버스에서 심볼이
 * 차지하는 영역만 잘라낸 것이다. 색은 `currentColor`라 버튼의 글자색을 그대로 따른다. */
function KakaoSymbol() {
  return (
    <svg viewBox="13 14 22 21" aria-hidden>
      <path
        d="M24.0014 14C17.9241 14 13 18.0219 13 22.9825C13 26.1711 15.0368 28.9728 18.1057 30.5656L17.0681 34.5677C17.0295 34.6871 17.0598 34.8151 17.1424 34.9033C17.2029 34.9659 17.2855 35 17.3653 35C17.4341 35 17.5029 34.9772 17.5607 34.9289L22.0196 31.8171C22.661 31.911 23.3215 31.9622 23.9986 31.9622C30.0732 31.9622 35 27.9403 35 22.9797C35 18.0191 30.0759 14 24.0014 14Z"
        fill="currentColor"
      />
    </svg>
  );
}

/** 카카오 브랜드 가이드가 정한 고정색이라 테마 토큰이 아니다 — 가이드가 컨테이너·심볼·레이블 색의 변경을
 * 금지하므로 다크에서도 같은 값을 쓴다(값은 카카오가 배포하는 공식 SVG의 `#FEE500`·`#191919`). 이 시스템의
 * 유채색 규칙 예외는 이 버튼에만 걸린다(`DESIGN.md` Colors 절) — 이 상수를 다른 UI가 가져다 쓰지 않는다.
 *
 * 호버에서도 색을 바꾸지 않는다. 가이드는 정해진 색 밖의 색을 금지하고 호버 변형을 따로 두지 않는다. 누름
 * 피드백은 `Button` 베이스의 `active:translate-y-px`가 진다. */
const KAKAO_BRAND_COLOR_CLASSNAME = "bg-[#FEE500] text-[#191919] hover:bg-[#FEE500]";

/** 카카오 로그인 버튼. `packages/ui`의 variant로 두지 않고 이 슬라이스에만 둔다 — 공용 어휘가 되면 노랑이
 * 다른 화면으로 번질 길이 생긴다.
 *
 * - 레이블은 "카카오 로그인"이다. 카카오 로그인 가이드가 허용하는 한국어 레이블은 "카카오 로그인"·"로그인"
 *   둘뿐이고 "카카오로 시작하기"는 카카오싱크 문구라, 가입 화면에서도 같은 레이블을 쓴다.
 * - 서체는 가이드의 "OS 기본 서체" 대신 이 시스템의 단일 서체를 따른다(버튼 베이스 그대로).
 * - 반경은 시스템 `lg`(8px)다. 공식 SVG가 46px 높이에 반경 8이고, 바로 아래 구글 버튼과 같은 높이 티어가
 *   같은 반경을 갖는 시스템 정책과도 맞는다. 높이도 구글 버튼과 같은 `size="lg"`다.
 * - 포커스는 `default` variant의 띄운 아웃라인(링 대신 2px 아웃라인을 2px 떨어뜨려 그림)을 물려받는다 — 베이스
 *   레시피의 핑크 보더는 다크에서 노랑 채움 대비 2.12:1, 50% 링은 배경 대비 3:1 미만이라 둘 다 WCAG 1.4.11에
 *   못 미친다. 띄운 틈에는 아래 표면이 비쳐 노랑 채움과 핑크 아웃라인 사이가 늘 표면 색으로 갈린다.
 * - 심볼–레이블 간격은 `gap-2`(8px) — 공식 SVG(46px 높이)의 실측 간격 약 7.9px에 맞췄다. */
export function KakaoLoginButton({ onClick }: KakaoLoginButtonProps) {
  return (
    <Button type="button" size="lg" className={`gap-2 ${KAKAO_BRAND_COLOR_CLASSNAME}`} onClick={onClick}>
      <KakaoSymbol />
      카카오 로그인
    </Button>
  );
}
