/**
 * 대소문자·유니코드 조합만 다른 글을 같은 것으로 보는 비교 키. 키워드 노트의 키워드 중복을 서버와 같게 가리고, 해시태그
 * 중복도 같은 키로 가린다(해시태그는 서버가 접어서 비교하지 않아 폼이 더 엄격할 뿐이다).
 *
 * 서버는 키워드를 NFC 로 맞춘 뒤 파이썬 `casefold()` 로 접어 비교하는데 JS 에는 casefold 가 없다. 소문자화만 하면 서버보다 느슨해(예: `ß`·`ẞ` 는 서버에서 `ss` 와 같다) 서버만 중복으로 보는 값을 폼이
 * 받아 자동저장이 거절된다. 소문자 → 대문자 → 소문자를 거치면 casefold 가 접는 모든 코드 포인트가 같은 키로
 * 모인다(전 코드 포인트 대조로 확인 — 소문자화만으로는 101개가 어긋났다). 반대로 폼이 더 엄격한 경우(점 없는
 * `ı` 와 `i` 등)는 서버가 받을 값을 폼이 막을 뿐이라 자동저장을 멈추지 않는다.
 */
export function caseFoldKey(value: string): string {
  return value.normalize("NFC").toLowerCase().toUpperCase().toLowerCase();
}
