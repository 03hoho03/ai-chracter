/** 클로버 충전(`pages/clover-hub` — 내 클로버의 무료 몫 아래와 클로버 안내)·내역(`pages/clover-history`)
 * 화면에 공통으로 뜨는 고지. 둘 다 리터럴로 "7일 뒤 소멸"을 복사해 갖고 있었는데, 2026-09-22
 * 게시된 공지("지급일로부터 **7~8일**이 지나면 소멸")와 어긋났다 — 만료 시각은 지급일 KST 자정
 * 기준으로 계산돼 실제 보유 기간이 받은 시각에 따라 7일~8일 사이가 되기 때문이다. 사본이
 * 둘이면 한쪽만 고치고 드리프트가 남는 실패가 이 저장소에 전례가 있어, 문구를 여기 한 곳으로
 * 모았다.
 *
 * 대상은 무료로 받는 지급분이다. 구매분은 5년 기한을 따로 갖고 어드민 지급·환불분은 만료가 없으므로 받는 길을 이름으로
 * 한정한다. 출석판이 꺼진 동안 무료로 받을 수 있는 길은 미션뿐이라 미션 기준으로 적는다(마이그레이션 백필분과 예전 무료
 * 지급분도 같은 규칙이다).
 *
 * 출석판이 켜지면 출석 클로버도 같은 규칙으로 만료되고, 같은 순간 시행되는 새 환불정책 게시본이 이 사실을 "받은 날부터
 * 7일 동안 쓸 수 있다"(받은 시각과 무관하게 누구나 누리는 최소 기간)로 말한다. 그래서 켜짐 문장은 새 게시본과 짝이고 꺼짐
 * 문장은 지금 게시본과 짝이다 — 어느 쪽을 고치든 게시본과 함께 맞춘다.
 *
 * 톤은 게시된 공지(`합니다`체)를 그대로 옮기지 않고 두 화면의 다른 문장들과 같은 `~요`체로
 * 맞췄다(같은 파일의 "아직 받은 클로버가 없어요" 등).
 *
 * `attendanceEnabled` 는 공개 가격 응답의 출석판 스위치다. 못 받았으면 꺼진 것으로 넘긴다(꺼진 동안 화면이 바뀌지 않게). */
export function formatCloverExpiryNotice(attendanceEnabled: boolean): string {
  return attendanceEnabled
    ? // "7일" 은 서버 `minValidDays` 를 읽지 않고 적는다 — 게시본 문장과 짝이라 서버 값만 바뀌어 게시본과 어긋나면 안 된다.
      "미션과 출석으로 받은 클로버는 받은 날부터 7일 동안 쓸 수 있어요."
    : "미션으로 받은 클로버는 지급일 자정 기준으로 7~8일 뒤 소멸돼요.";
}
